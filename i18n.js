const DEFAULT_LANGUAGE = "en";
const SUPPORTED_LANGUAGES = Object.keys(translations);

function getTranslation(obj, path) {
  return path.split(".").reduce((acc, part) => (acc ? acc[part] : undefined), obj);
}

function translate(path, lang) {
  const selectedValue = getTranslation(translations[lang], path);
  const fallbackValue = getTranslation(translations[DEFAULT_LANGUAGE], path);

  return selectedValue ?? fallbackValue ?? path;
}

function getInitialLanguage() {
  const savedLanguage = getSavedLanguage();

  if (SUPPORTED_LANGUAGES.includes(savedLanguage)) {
    return savedLanguage;
  }

  const browserLanguage = (navigator.language || navigator.userLanguage || "").toLowerCase();

  if (browserLanguage.startsWith("ru")) {
    return "ru";
  }

  return DEFAULT_LANGUAGE;
}

function updateMetadata(lang) {
  const description = document.querySelector('meta[name="description"]');

  document.documentElement.lang = lang;
  document.title = translate("meta.title", lang);

  if (description) {
    description.setAttribute("content", translate("meta.description", lang));
  }
}

function updateLanguageButtons(lang) {
  document.querySelectorAll("[data-lang]").forEach((button) => {
    const isActive = button.dataset.lang === lang;

    button.setAttribute("aria-pressed", String(isActive));
    button.classList.toggle("is-active", isActive);
  });
}

function applyTranslations(lang) {
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translate(element.dataset.i18n, lang);
  });

  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    element.innerHTML = translate(element.dataset.i18nHtml, lang);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", translate(element.dataset.i18nAriaLabel, lang));
  });

  document.querySelectorAll("[data-i18n-title]").forEach((element) => {
    element.setAttribute("title", translate(element.dataset.i18nTitle, lang));
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.setAttribute("placeholder", translate(element.dataset.i18nPlaceholder, lang));
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.setAttribute("alt", translate(element.dataset.i18nAlt, lang));
  });
}

function setLanguage(lang) {
  const nextLanguage = SUPPORTED_LANGUAGES.includes(lang) ? lang : DEFAULT_LANGUAGE;

  saveLanguage(nextLanguage);
  updateMetadata(nextLanguage);
  applyTranslations(nextLanguage);
  updateLanguageButtons(nextLanguage);
}

function getSavedLanguage() {
  try {
    return localStorage.getItem("lang");
  } catch (error) {
    return null;
  }
}

function saveLanguage(lang) {
  try {
    localStorage.setItem("lang", lang);
  } catch (error) {
    // Language switching should still work when storage is unavailable.
  }
}

document.addEventListener("DOMContentLoaded", () => {
  setLanguage(getInitialLanguage());

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.addEventListener("click", () => {
      setLanguage(button.dataset.lang);
    });
  });
});

window.setLanguage = setLanguage;
